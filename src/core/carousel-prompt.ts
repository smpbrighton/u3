export function resolveCarouselPrompt(saved: unknown, fallback: string): string {
  return typeof saved === "string" && saved.trim() ? saved : fallback;
}

export function carouselTopicPrompt(options: { basePrompt: string; count: number; topic: string; style?: string }): string {
  return `${options.basePrompt}\n\n요청 장수: ${options.count}\n주제: ${options.topic}${options.style ? `\n요청 화풍: ${options.style}` : ""}`;
}

